import sys
from pathlib import Path
root=Path(__file__).parent
sys.path.insert(0,str(root/'vendor'))
from playwright.sync_api import sync_playwright,expect
with sync_playwright() as p:
    browser=p.chromium.launch(channel='chrome',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':900})
    page.route('**/*',lambda r:r.continue_() if r.request.url.startswith('http://localhost/') else r.abort())
    page.goto('http://localhost/bookverse/san-pham-gom/',wait_until='domcontentloaded')
    if not page.locator('.bv-header-account').count():
        print(page.locator('body').inner_text()[:1800],flush=True)
    expect(page.locator('#regester')).to_have_count(0)
    page.locator('.bv-header-account').hover()
    expect(page.locator('#bv-account-panel')).to_be_visible()
    assert not page.locator('#bv-account-panel').evaluate('(e)=>e.matches(":modal")')
    page.locator('#bv-panel-username').hover()
    page.wait_for_timeout(400)
    expect(page.locator('#bv-account-panel')).to_be_visible()
    page.locator('.bv-header-cart').hover()
    expect(page.locator('#bv-cart-panel')).to_be_visible()
    expect(page.locator('#bv-account-panel')).not_to_be_visible()
    page.mouse.move(30,500)
    expect(page.locator('#bv-cart-panel')).not_to_be_visible()
    page.evaluate('scrollTo(0,700)')
    page.wait_for_timeout(500)
    page.locator('.bv-header-account').hover()
    page.screenshot(path=str(root/'header-hover.png'))
    page.keyboard.press('Escape')
    expect(page.locator('#bv-account-panel')).not_to_be_visible()
    mobile=browser.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    mobile.route('**/*',lambda r:r.continue_() if r.request.url.startswith('http://localhost/') else r.abort())
    mobile.goto('http://localhost/bookverse/san-pham-gom/',wait_until='domcontentloaded')
    mobile.locator('.bv-header-account').tap()
    expect(mobile.locator('#bv-account-panel')).to_be_visible()
    assert mobile.locator('#bv-account-panel').evaluate('(e)=>e.matches(":modal")')
    assert mobile.evaluate('document.documentElement.scrollWidth<=innerWidth')
    mobile.screenshot(path=str(root/'header-hover-mobile.png'))
    browser.close()
    print('PASS: booking removed, hover panels, pointer transfer, close, compact header and touch fallback.')
